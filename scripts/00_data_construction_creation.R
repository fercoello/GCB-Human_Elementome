UNdata_bitumen <- read_csv("data/data_construction/UNdata_Export_20260122_111521360/UNdata_Export_20260122_111521360.csv") %>%
  rename(Country = 1, Commodity = 2, Year = 3, Unit = 4, Value = 5)

## Cement production --------------------------------------------------------

# Global cement-production statistics were obtained from the United States
# Geological Survey (USGS). These data are used to extend concrete-related
# aggregate demand beyond the 1900–2016 series of Plank et al. (2022) and to
# estimate clay and limestone demand associated with cement production.
#
# Concrete aggregate demand is estimated using a cement-to-aggregate mass ratio
