### Screen observations and interpolate missing years -----------------------

# Complete annual national time series and linearly interpolate intermediate
# missing years.
#
# Very high reported observations are additionally screened within each
# country. Observations exceeding the 90th percentile plus three SD of reported
# railway length are treated as potential outliers, removed, and interpolated
# from neighbouring years.

rail_full_complete <- rail_full_clean %>%
  group_by(Country) %>%
  complete(
    Year = full_seq(Year, 1)
  ) %>%
  arrange(
    Year,
    .by_group = TRUE
  ) %>%
  mutate(
    Length_km_original = Length_km,
    was_real = !is.na(Length_km_original),
    
    p90_real = quantile(
      Length_km_original[was_real],
      0.90,
      na.rm = TRUE
    ),
    
    sd_real = sd(
      Length_km_original[was_real],
      na.rm = TRUE
    ),
    
    upper_thr = p90_real + 3 * sd_real,
    
    outlier_high =
      was_real &
      Length_km_original > upper_thr,
    
    Length_km_clean = if_else(
      outlier_high,
      NA_real_,
      Length_km_original
    ),
    
    Length_km = na.approx(
      Length_km_clean,
      x = Year,
      na.rm = FALSE
    ),
    
    data_type = case_when(
      was_real & !outlier_high ~ "real",
      outlier_high ~ "outlier_removed_interpolated",
      !was_real ~ "interpolated"
    )
  ) %>%
  ungroup() %>%
  select(
    -p90_real,
    -sd_real,
    -upper_thr
  )
### Estimate annual additions and filter discontinuities --------------------

# Annual additions are calculated as year-to-year changes in railway length.
#
# Large positive jumps may reflect changes in national boundaries, statistical
# coverage, or inconsistencies between historical sources rather than actual
# construction. Jumps larger than 500 km and 10% of the country's maximum
# railway length are therefore flagged.
#
# For flagged years, cumulative negative changes within a ±10-year window are
# examined. If these losses exceed 10% of maximum network length, the positive
# jump is treated as an artefact and assigned zero additional railway length.
#
# Negative annual changes are also set to zero because this reconstruction
# targets newly added railway rather than net changes in network length.

rail_diff <- rail_full_complete %>%
  group_by(Country) %>%
  arrange(
    Year,
    .by_group = TRUE
  ) %>%
  mutate(
    diff_km = Length_km - lag(Length_km),
    
    max_length = max(
      Length_km,
      na.rm = TRUE
    ),
    
    pct_max = diff_km / max_length,
    
    suspicious = if_else(
      !is.na(diff_km) &
        diff_km > RAIL_JUMP_KM &
        pct_max > RAIL_JUMP_PROP,
      TRUE,
      FALSE
    )
  ) %>%
  group_modify(
    ~ {
      df <- .x
      
      df %>%
        mutate(
          neg_nearby_10y = map_lgl(
            seq_len(n()),
            function(i) {
              
              yr_i <- df$Year[i]
              
              window <- df %>%
                filter(
                  Year >= yr_i - RAIL_JUMP_WINDOW,
                  Year <= yr_i + RAIL_JUMP_WINDOW,
                  Year != yr_i
                )
              
              cum_neg <- sum(
                window$diff_km[
                  window$diff_km < 0
                ],
                na.rm = TRUE
              )
              
              (cum_neg / df$max_length[i]) <
                -RAIL_JUMP_PROP
            }
          )
        )
    }
  ) %>%
  ungroup() %>%
  mutate(
    added_km = case_when(
      suspicious & neg_nearby_10y ~ 0,
      diff_km < 0 ~ 0,
      TRUE ~ diff_km
    )
  )



