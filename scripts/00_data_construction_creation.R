Railway_gauges <- read_excel("data/source_compilations/Railway_length_gauge_world.xlsx", sheet = "Gauge")


# 02. Clay: brick production ------------------------------------------------

# Historical global brick production was obtained from Plank et al. (2022):
# https://doi.org/10.1016/j.resconrec.2021.106122
#
# The source provides annual global estimates of brick, concrete, and asphalt
# production for 1900–2016, together with coefficients of variation (CVs) used
# here to represent uncertainty.
#
# Brick production is used to estimate clay demand associated with bricks.
# Outside the temporal coverage of Plank et al. (2022), brick production is
# extrapolated using global population and constant per-capita production rates
# derived from the boundary years of the source series.


## Aggregate material categories --------------------------------------------

# Sum all source columns corresponding to concrete, asphalt, and bricks while
# retaining the annual CV reported by Plank et al. (2022).
#
# Concrete and asphalt totals are retained because they are subsequently used
# in the aggregate reconstruction.

data_aggregate <- data_construction_resrecenv %>%
  mutate(
    Concrete_total = rowSums(
      select(., starts_with("Concrete")),
      na.rm = TRUE
    ),
    Asphalt_total = rowSums(
      select(., starts_with("Asphalt")),
      na.rm = TRUE
    ),
    Brick_total = rowSums(
      select(., starts_with("Brick")),
      na.rm = TRUE
    )
  ) %>%
  select(
    Year,
    Concrete_total,
    Asphalt_total,
    Brick_total,
    CV
  )


## Extend brick-production series -------------------------------------------

# For years before 1900, the per-capita brick-production rate observed at the
# beginning of the Plank et al. (2022) series is applied to global population.
#
# For years after 2016, the corresponding rate at the end of the series is
# applied.
#
# The CVs from the boundary years are similarly propagated backward and
# forward to characterize uncertainty outside the original data coverage.
#
# Brick production is converted from Mt to Gt. Brick mass is assumed to
# represent clay demand directly (1:1 mass relationship).

data_brick <- data_aggregate %>%
  select(
    Year,
    Brick_total,
    CV
  ) %>%
  right_join(
    population_OWD,
    by = "Year"
  ) %>%
  mutate(
    brick_per_capita = Brick_total / Population,
    
    Brick_total = case_when(
      Year < 1900 ~ BRICK_PC_1900 * Population,
      Year > 2016 ~ BRICK_PC_2016 * Population,
      TRUE ~ Brick_total
    ),
    
    CV = case_when(
      Year < 1900 ~ BRICK_CV_1900,
      Year > 2016 ~ BRICK_CV_2016,
      TRUE ~ CV
    ),
    
    # Convert Mt to Gt
    Brick_total = Brick_total * 1e-3,
    
    # Clay demand associated with brick production
    clay_brick = Brick_total,
    clay_brick_sd = clay_brick * CV
  ) %>%
  arrange(Year)


# 03. Aggregates ------------------------------------------------------------

# Global aggregate extraction is reconstructed from four major uses:
#   1. concrete production;
#   2. asphalt production;
#   3. road-base and building-subbase construction; and
#   4. railway ballast.
#
# Concrete and asphalt estimates are based primarily on Plank et al. (2022),
# while road and building bases follow the material-intensity assumptions of
# Krausmann et al. (2017) and Miatto et al. (2017).
#
# Only virgin aggregate extraction is ultimately retained in order to avoid
# counting recycled or reused construction materials as new lithospheric
# mobilization.


## Concrete and asphalt -----------------------------------------------------

# Plank et al. (2022) provide historical global concrete and asphalt
# production for 1900–2016.
#
# To extend these series backward, concrete production is assumed to begin in
# 1850 and asphalt production in 1870, following the historical assumptions
# adopted by Plank et al. Production is linearly increased from zero in the
# respective starting year to the value reported for 1900.
#
# The 1900 CV is propagated backward to characterize uncertainty before the
# beginning of the original Plank et al. series.


# Helper function: linear increase from zero at `start_year` to the observed
# value in 1900.

ramp_to_1900 <- function(year, start_year, value_1900) {
  
  case_when(
    year < start_year ~ 0,
    year <= PLANK_START_YEAR ~
      (year - start_year) /
      (PLANK_START_YEAR - start_year) *
      value_1900,
    TRUE ~ NA_real_
  )
}


# Create a complete annual series beginning in 1850.

construction_years <- tibble(
  Year = seq(
    CONCRETE_START_YEAR,
    max(data_aggregate$Year, na.rm = TRUE)
  )
)

data_aggregate_expanded <- construction_years %>%
  left_join(
    data_aggregate %>%
      select(
        Year,
        Concrete_total,
        Asphalt_total,
        CV
      ),
    by = "Year"
  )


# Extract the first observed values from the Plank et al. series.

concrete_1900 <- data_aggregate %>%
  filter(Year == PLANK_START_YEAR) %>%
  pull(Concrete_total) %>%
  first()

asphalt_1900 <- data_aggregate %>%
  filter(Year == PLANK_START_YEAR) %>%
  pull(Asphalt_total) %>%
  first()


# Reconstruct concrete and asphalt production before 1900 and convert the
# original production units from Mt to Gt.

data_aggregate_expanded <- data_aggregate_expanded %>%
  mutate(
    Concrete_total = if_else(
      Year < PLANK_START_YEAR,
      ramp_to_1900(
        Year,
        start_year = CONCRETE_START_YEAR,
        value_1900 = concrete_1900
      ),
      Concrete_total
    ),
    
    Asphalt_total = if_else(
      Year < PLANK_START_YEAR,
      ramp_to_1900(
        Year,
        start_year = ASPHALT_START_YEAR,
        value_1900 = asphalt_1900
      ),
      Asphalt_total
    ),
    
    CV = if_else(
      Year < PLANK_START_YEAR,
      BRICK_CV_1900,
      CV
    ),
    
    # Convert Mt to Gt
    Concrete_total = Concrete_total * 1e-3,
    Asphalt_total = Asphalt_total * 1e-3,
    
    Concrete_total_sd = Concrete_total * CV,
    Asphalt_total_sd = Asphalt_total * CV
  )

## Extend concrete and asphalt beyond 2016 ----------------------------------

# For 2017 onward, concrete production is reconstructed from global USGS
# cement-production statistics. A cement-to-aggregate ratio of 1:5 implies
# that total concrete mass is six times the cement mass.
#
# Asphalt production is reconstructed from UN statistics on bitumen used for
# non-energy purposes. A bitumen-to-aggregate ratio of 1:19 implies that total
# asphalt mass is 20 times the bitumen mass.
#
# These relationships follow Plank et al. (2022). Their performance was checked
# against the Plank et al. series during overlapping years before applying them
# beyond 2016.
#
# The CV from the final year of the Plank et al. series is propagated forward
# to characterize uncertainty.


# Asphalt from UN bitumen statistics.

data_bitumen_post2016 <- UNdata_bitumen %>%
  filter(
    Commodity == "Bitumen - Non-energy uses",
    Year > 1990
  ) %>%
  group_by(Year) %>%
  summarise(
    bitumen_production = sum(Value, na.rm = TRUE) * 1e-3,
    .groups = "drop"
  ) %>%
  mutate(
    Asphalt_total =
      bitumen_production / (1 - ASPHALT_AGGREGATE_FRACTION)
  )


# Concrete from USGS cement statistics.

data_cement_post2016 <- USGS_cement %>%
  transmute(
    Year,
    cement = Value,
    Concrete_total =
      cement / (1 - CONCRETE_AGGREGATE_FRACTION)
  ) %>%
  drop_na()


# Combine the reconstructed post-2016 concrete and asphalt series.

data_aggregates_post2016 <- data_cement_post2016 %>%
  filter(Year > PLANK_END_YEAR) %>%
  select(
    Year,
    Concrete_total
  ) %>%
  left_join(
    data_bitumen_post2016 %>%
      filter(Year > PLANK_END_YEAR) %>%
      select(
        Year,
        Asphalt_total
      ),
    by = "Year"
  ) %>%
  mutate(
    CV = BRICK_CV_2016,
    Concrete_total_sd = Concrete_total * CV,
    Asphalt_total_sd = Asphalt_total * CV
  )

## Combine concrete and asphalt series --------------------------------------

data_concrete_asphalt <- bind_rows(
  data_aggregate_expanded %>%
    filter(Year <= PLANK_END_YEAR),
  data_aggregates_post2016
) %>%
  arrange(Year) %>%
  mutate(
    # Aggregate fraction of total concrete and asphalt mass
    aggregates_concrete =
      Concrete_total * CONCRETE_AGGREGATE_FRACTION,
    
    aggregates_asphalt =
      Asphalt_total * ASPHALT_AGGREGATE_FRACTION,
    
    aggregates_concrete_sd =
      Concrete_total_sd * CONCRETE_AGGREGATE_FRACTION,
    
    aggregates_asphalt_sd =
      Asphalt_total_sd * ASPHALT_AGGREGATE_FRACTION
  )

## Road-base aggregates -----------------------------------------------------

# Aggregate demand for asphalt-road base courses is estimated from bitumen
# consumption following Krausmann et al. (2017) and Miatto et al. (2017).
#
# The aggregate-to-bitumen ratio is assumed to be:
#   - 100:1 before 1940;
#   - linearly declining from 100:1 to 50:1 during 1940–1980;
#   - 50:1 from 1980 onward.
#
# Bitumen represents 5% of total asphalt mass in the Plank et al. formulation.
# A relative uncertainty of ±30% (1 SD) is applied following Krausmann et al.
# (2017).


road_base_ratio <- tibble(
  Year = data_concrete_asphalt$Year
) %>%
  mutate(
    aggregate_to_bitumen = case_when(
      Year < ROAD_BASE_TRANSITION_START ~ ROAD_BASE_RATIO_PRE1940,
      
      Year >= ROAD_BASE_TRANSITION_END ~ ROAD_BASE_RATIO_POST1980,
      
      TRUE ~
        ROAD_BASE_RATIO_PRE1940 +
        (Year - ROAD_BASE_TRANSITION_START) *
        (
          ROAD_BASE_RATIO_POST1980 -
            ROAD_BASE_RATIO_PRE1940
        ) /
        (
          ROAD_BASE_TRANSITION_END -
            ROAD_BASE_TRANSITION_START
        )
    )
  )


aggregates_base_roads <- data_concrete_asphalt %>%
  left_join(
    road_base_ratio,
    by = "Year"
  ) %>%
  mutate(
    aggregate_base_road =
      Asphalt_total *
      ROAD_BASE_BITUMEN_FRACTION *
      aggregate_to_bitumen,
    
    aggregate_base_road_sd =
      aggregate_base_road * ROAD_BASE_CV
  ) %>%
  select(
    Year,
    aggregate_base_road,
    aggregate_base_road_sd
  )

## Building-subbase aggregates ---------------------------------------------

# Aggregate demand associated with building subbase layers is estimated from
# concrete and brick production following Krausmann et al. (2017), based on
# Miatto et al. (2017).
#
# Aggregate requirements are assumed to correspond to:
#   - 0.07 units of aggregate per unit of concrete;
#   - 0.045 units of aggregate per unit of bricks.
#
# A relative uncertainty of ±33% (1 SD) is applied to the combined estimate.

aggregates_base_buildings <- data_brick %>%
  select(
    Year,
    Brick_total
  ) %>%
  full_join(
    data_concrete_asphalt %>%
      select(
        Year,
        Concrete_total
      ),
    by = "Year"
  ) %>%
  mutate(
    Brick_total = replace_na(Brick_total, 0),
    Concrete_total = replace_na(Concrete_total, 0),
    
    aggregate_brick =
      Brick_total * BUILDING_BASE_BRICK_RATIO,
    
    aggregate_concrete =
      Concrete_total * BUILDING_BASE_CONCRETE_RATIO,
    
    aggregates_base_buildings =
      aggregate_brick + aggregate_concrete,
    
    aggregates_base_buildings_sd =
      aggregates_base_buildings * BUILDING_BASE_CV
  ) %>%
  select(
    Year,
    aggregates_base_buildings,
    aggregates_base_buildings_sd,
    aggregate_concrete,
    aggregate_brick
  )

## Virgin aggregate extraction ---------------------------------------------

# Road and building-base demand can partly be supplied by recycled or reused
# construction materials. Because the objective is to estimate mobilization
# from the lithosphere, only the fraction supplied by virgin aggregates is
# retained.
#
# Virgin aggregate fractions are taken from Krausmann et al. (2017).
# The earliest available value (1900) is propagated backward, and the latest
# available value (2010) is propagated forward beyond the source coverage.
#
# Uncertainties in road-base and building-subbase demand are treated as
# independent and combined by quadrature.

aggregates_bases <- full_join(
  aggregates_base_buildings,
  aggregates_base_roads,
  by = "Year"
) %>%
  mutate(
    across(
      c(
        aggregates_base_buildings,
        aggregates_base_buildings_sd,
        aggregate_base_road,
        aggregate_base_road_sd
      ),
      ~ replace_na(.x, 0)
    )
  ) %>%
  left_join(
    Krausmann_recycling %>%
      select(
        Year,
        Sand_gravel_Virgin_perc
      ),
    by = "Year"
  ) %>%
  mutate(
    Sand_gravel_Virgin_perc = case_when(
      Year < 1901 ~ VIRGIN_AGGREGATE_1900,
      Year > 2010 ~ VIRGIN_AGGREGATE_2010,
      TRUE ~ Sand_gravel_Virgin_perc
    ),
    
    aggregate_bases_all =
      aggregates_base_buildings +
      aggregate_base_road,
    
    aggregate_bases_sd = sqrt(
      aggregates_base_buildings_sd^2 +
        aggregate_base_road_sd^2
    ),
    
    aggregate_bases_virgin =
      aggregate_bases_all *
      Sand_gravel_Virgin_perc,
    
    aggregate_bases_virgin_sd =
      aggregate_bases_sd *
      Sand_gravel_Virgin_perc
  ) %>%
  arrange(Year)

## Railway ballast ----------------------------------------------------------

# Historical national railway-length series are combined with recent World
# Bank data to reconstruct annual railway additions. Missing intermediate years
# are interpolated, and implausible observations or discontinuities are filtered
# before estimating newly constructed railway length.
#
# Country-specific railway gauges are then used to estimate aggregate demand
# for railway ballast. Ballast associated with both new construction and
# maintenance/renewal is included.
### Functions ---------------------------
sd_from_range <- function(
    min_value,
    max_value,
    coverage = MC_COVERAGE_RAIL
) {
  
  z <- qnorm((1 + coverage) / 2)
  
  (max_value - min_value) /
    (2 * z)
}


rnorm_trunc0 <- function(
    n,
    mean,
    sd
) {
  
  if (is.na(mean) || is.na(sd)) {
    return(rep(NA_real_, n))
  }
  
  if (sd <= 0) {
    return(rep(max(mean, 0), n))
  }
  
  truncnorm::rtruncnorm(
    n,
    a = 0,
    b = Inf,
    mean = mean,
    sd = sd
  )
}
