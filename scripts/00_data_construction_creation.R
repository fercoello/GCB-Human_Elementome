# Purpose:
#   Reconstruct annual global mass series for construction materials used in
#   the elemental-mobilization analysis. The workflow estimates the extraction
#   and use of aggregates, clay, and carbonate rocks associated with concrete,
#   asphalt, bricks, road and building bases, railway ballast, cement, and lime.
#
#   The reconstruction integrates published material-flow estimates,
#   mineral-production statistics, population data, railway statistics, and
#   literature-derived engineering assumptions. Missing periods are reconstructed
#   using interpolation, extrapolation, or source-specific assumptions documented
#   in the Supplementary Methods and within the corresponding workflow sections.
#
# Analytical framework:
#   Annual material-use series are reconstructed separately for:
#     - aggregates;
#     - clay; and
#     - carbonate rocks represented by the reconstructed limestone series.
#
#   Uncertainty in the reconstructed material masses is propagated where
#   applicable using Monte Carlo simulation or source-specific uncertainty
#   estimates. The resulting annual best estimates and SDs are used as inputs
#   by `01_Elemental_Mobilization.R`.
#
# Units:
#   Final construction-material mass series are expressed in Tg yr-1.
#   Intermediate calculations may use tonnes, Tg, km, population-based rates,
#   or other source-specific units; conversions are documented where applied.
#
# Temporal coverage:
#   Annual series are reconstructed over the historical period required by the
#   elemental-mobilization analysis, subject to the temporal coverage of the
#   underlying source datasets.
